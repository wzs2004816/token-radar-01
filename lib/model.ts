// Token Radar — model radar-2.
//
// One sealed snapshot in, one ranked board out. The board ranks pre-token
// protocols by an implied value that follows only from the snapshot's own
// figures: TVL, seven-day TVL growth, how long the protocol has run with no
// token, and how many chains its TVL sits on. No protocol name is ever
// special-cased; the same function scores every row.
//
//   implied = round( tvl_usd x 0.28
//                    x (1 + clamp(change_7d, -50, 150) / 100 x 0.6)
//                    x (0.55 + min(age_days, 1460) / 1460 x 0.45)
//                    x (1 + min(chains - 1, 5) x 0.03) )
//
// Age is days since DefiLlama first listed the protocol; an unknown age
// counts as 365 days. A protocol is pre-token when its record carries no
// market cap, no CoinGecko id and no symbol.
//
// Beside the value, every row carries two computed readings:
//   - a risk score 0-100 (higher is riskier) built from shrinking TVL,
//     parabolic growth, young age, single-chain concentration and thin TVL;
//   - five launch-readiness checks (no token on record, TVL at or above the
//     watchlist floor, multi-chain, seasoned, growing), each a plain fact
//     from the snapshot.
//
// The board covers every watchlist slug (the floor, never the ceiling) and
// adds the strongest pre-token protocols below the floor, by TVL, so the
// radar finds early launches instead of only repeating the watchlist.

/** One protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, stated in the dashboard so a reader can check them. */
